/**
 * Downloads equipment photos listed in a sync manifest, transcodes them, files
 * them under public/images/equipment/<code>/, and writes the resulting photos[]
 * arrays back into src/data/equipment.source.json.
 *
 *   node scripts/fetch-equipment-photos.mjs [options]
 *
 *   --manifest <path>   default scripts/.sync/photo-manifest.json
 *   --only A,B          process only these item codes
 *   --dry-run           validate the manifest against the JSON, fetch nothing
 *   --no-json           write images only, leave equipment.source.json alone
 *   --prune-orphans     delete folders for codes absent from the manifest
 *   --max-total-mb <n>  hard stop on total bytes written (default 25)
 *
 * WHY A SCRIPT WRITES THE JSON, not the agent that reads Notion:
 *   - width/height only exist after the resize
 *   - if a signed URL expires mid-run, only the script knows which files really
 *     landed; an agent writing blind would reference a file that isn't there
 *   - deriving the path in code makes a wrong-case folder structurally
 *     impossible, instead of relying on someone typing lowercase every time
 *
 * It is deliberately .mjs: it runs on plain node (no tsx, no npx prompt) and
 * stays out of `tsc --noEmit`, which only includes TypeScript sources.
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";

const ROOT = process.cwd();
const JSON_PATH = path.join(ROOT, "src", "data", "equipment.source.json");
const OUT_ROOT = path.join(ROOT, "public", "images", "equipment");

const LONGEST_EDGE = 1600;
const QUALITY_LADDER = [78, 70, 62];
const SOFT_MAX_BYTES = 400_000;
const CONCURRENCY = 4;
const FETCH_TIMEOUT_MS = 60_000;
const RETRY_DELAYS_MS = [1000, 3000, 8000];

/* ── args ─────────────────────────────────────────────────────────────────── */

function parseArgs(argv) {
  const o = {
    manifest: path.join(ROOT, "scripts", ".sync", "photo-manifest.json"),
    only: null,
    dryRun: false,
    writeJson: true,
    pruneOrphans: false,
    maxTotalMb: 25,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--manifest") o.manifest = path.resolve(argv[++i]);
    else if (a === "--only") o.only = new Set(argv[++i].split(",").map((s) => s.trim()));
    else if (a === "--dry-run") o.dryRun = true;
    else if (a === "--no-json") o.writeJson = false;
    else if (a === "--prune-orphans") o.pruneOrphans = true;
    else if (a === "--max-total-mb") o.maxTotalMb = Number(argv[++i]);
    else die(`unknown option: ${a}`);
  }
  return o;
}

function die(msg) {
  console.error(`\nHALT: ${msg}\n`);
  process.exit(1);
}

const args = parseArgs(process.argv.slice(2));

/* ── load + cross-check ───────────────────────────────────────────────────── */

if (!fs.existsSync(args.manifest)) {
  die(
    `manifest not found at ${path.relative(ROOT, args.manifest)}\n` +
      `It is generated by the agent while reading Notion — see scripts/sync-equipment.md.`
  );
}

const manifest = JSON.parse(fs.readFileSync(args.manifest, "utf8"));
const data = JSON.parse(fs.readFileSync(JSON_PATH, "utf8"));

if (manifest.version !== 1) die(`unsupported manifest version ${manifest.version}`);
if (!Array.isArray(manifest.items)) die("manifest.items must be an array");

const rowByCode = new Map(data.rows.map((r) => [r.code, r]));
const seenCodes = new Set();

for (const item of manifest.items) {
  const where = `item ${item.code || "(no code)"}`;
  if (!item.code) die(`${where}: missing code`);
  if (seenCodes.has(item.code)) die(`${where}: duplicate code in manifest`);
  seenCodes.add(item.code);

  // Halt rather than silently skip: a code mismatch means the agent's rows and
  // the manifest disagree, and guessing which is right is not the script's job.
  if (!rowByCode.has(item.code)) {
    die(`${where}: no row with this code in equipment.source.json`);
  }
  if (!/^[a-z0-9-]+$/.test(item.code.toLowerCase())) {
    die(`${where}: code does not lowercase to [a-z0-9-]+ — it becomes a folder name`);
  }

  const photos = item.photos ?? [];
  if (photos.length > 8) die(`${where}: ${photos.length} photos — cap is 8 (design target 6)`);

  const urls = new Set();
  for (const [j, p] of photos.entries()) {
    const at = `${where} photo ${j}`;
    // https only, with a localhost exception so the pipeline can be exercised
    // against a local fixture server. A signed Notion URL is never localhost,
    // so this cannot weaken the real guard.
    const isLocal = /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\//.test(p.url ?? "");
    if (!p.url?.startsWith("https://") && !isLocal) {
      die(`${at}: url must be https:// (or http://127.0.0.1 for local fixtures)`);
    }
    if (urls.has(p.url)) die(`${at}: duplicate url within the item`);
    urls.add(p.url);
    if (!p.alt?.trim()) die(`${at}: alt is required and must be non-empty`);
  }
}

const targets = manifest.items.filter((i) => !args.only || args.only.has(i.code));
if (args.only) {
  for (const code of args.only) {
    if (!seenCodes.has(code)) die(`--only names ${code}, which is not in the manifest`);
  }
}

if (args.dryRun) {
  const n = targets.reduce((s, i) => s + (i.photos?.length ?? 0), 0);
  console.log(`Manifest OK — ${targets.length} items, ${n} photos, all codes resolve.`);
  process.exit(0);
}

/* ── fetch ────────────────────────────────────────────────────────────────── */

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function sniff(buf) {
  if (buf.length < 12) return null;
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "jpeg";
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])))
    return "png";
  if (buf.subarray(0, 4).toString("ascii") === "RIFF" && buf.subarray(8, 12).toString("ascii") === "WEBP")
    return "webp";
  const ftyp = buf.subarray(4, 12).toString("ascii");
  if (ftyp.startsWith("ftypheic") || ftyp.startsWith("ftypheix") || ftyp.startsWith("ftypmif1"))
    return "heic";
  if (buf.subarray(0, 5).toString("ascii").trim().startsWith("<")) return "markup";
  return null;
}

/** Returns a Buffer, or throws with a classified `.reason`. */
async function download(url) {
  let lastErr;
  for (let attempt = 0; attempt <= RETRY_DELAYS_MS.length; attempt++) {
    try {
      const res = await fetch(url, {
        signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
        redirect: "follow",
      });
      // 403/404 on a signed Notion URL means it expired. Retrying only burns
      // the remaining window on the other URLs — fail fast and report.
      if (res.status === 403 || res.status === 404) {
        const e = new Error(`HTTP ${res.status}`);
        e.reason = "EXPIRED";
        throw e;
      }
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return Buffer.from(await res.arrayBuffer());
    } catch (err) {
      if (err.reason === "EXPIRED") throw err;
      lastErr = err;
      if (attempt < RETRY_DELAYS_MS.length) await sleep(RETRY_DELAYS_MS[attempt]);
    }
  }
  lastErr.reason = "FETCH";
  throw lastErr;
}

async function transcode(buf) {
  const kind = sniff(buf);
  if (kind === "heic") {
    const e = new Error("HEIC/HEIF is not decodable by the bundled sharp build");
    e.reason = "HEIC";
    throw e;
  }
  if (kind === "markup" || kind === null) {
    const e = new Error("not a JPEG/PNG/WebP (an error page or an unsupported format?)");
    e.reason = "FORMAT";
    throw e;
  }

  for (const quality of QUALITY_LADDER) {
    const { data: out, info } = await sharp(buf, { failOn: "none" })
      // .rotate() with no argument bakes in the EXIF orientation. It MUST come
      // before .resize(), or a portrait shot gets resized on the wrong axis.
      // sharp drops metadata by default, so EXIF/GPS are stripped for free —
      // do not add .withMetadata().
      .rotate()
      .resize({
        width: LONGEST_EDGE,
        height: LONGEST_EDGE,
        fit: "inside",
        withoutEnlargement: true,
      })
      .jpeg({ quality, mozjpeg: true, chromaSubsampling: "4:2:0" })
      .toBuffer({ resolveWithObject: true });

    if (info.size <= SOFT_MAX_BYTES || quality === QUALITY_LADDER.at(-1)) {
      return { out, info, quality };
    }
  }
}

async function pool(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length) {
        const i = next++;
        results[i] = await worker(items[i], i);
      }
    })
  );
  return results;
}

/* ── run ──────────────────────────────────────────────────────────────────── */

const report = [];
const problems = [];
let totalBytes = 0;

for (const item of targets) {
  const photos = item.photos ?? [];
  const dirName = item.code.toLowerCase();
  const dir = path.join(OUT_ROOT, dirName);

  const fetched = await pool(photos, CONCURRENCY, async (p) => {
    try {
      const buf = await download(p.url);
      const { out, info, quality } = await transcode(buf);
      return { ok: true, p, out, info, quality };
    } catch (err) {
      return { ok: false, p, reason: err.reason ?? "FETCH", message: err.message };
    }
  });

  const good = fetched.filter((r) => r.ok);
  const bad = fetched.filter((r) => !r.ok);

  for (const b of bad) {
    problems.push({ code: item.code, file: b.p.fileName ?? b.p.url, reason: b.reason, message: b.message });
  }

  if (good.length > 0) fs.mkdirSync(dir, { recursive: true });

  // Number AFTER collecting successes, so a failed photo leaves no gap.
  const written = [];
  for (const [i, r] of good.entries()) {
    const name = `${String(i + 1).padStart(2, "0")}.jpg`;
    const tmp = path.join(dir, `${name}.tmp`);
    // tmp + rename is atomic: an interrupted run can never leave a truncated
    // JPEG that would satisfy the validator's non-empty check.
    fs.writeFileSync(tmp, r.out);
    fs.renameSync(tmp, path.join(dir, name));
    totalBytes += r.info.size;
    written.push({
      src: `/images/equipment/${dirName}/${name}`,
      alt: r.p.alt.trim(),
      width: r.info.width,
      height: r.info.height,
      ...(r.p.caption?.trim() ? { caption: r.p.caption.trim() } : {}),
      _bytes: r.info.size,
      _quality: r.quality,
      _from: r.p.fileName ?? "",
    });
  }

  // Only prune when the item was fully successful: a transient failure on
  // photo 3 must not delete last week's perfectly good 03.jpg.
  if (bad.length === 0 && fs.existsSync(dir)) {
    const keep = new Set(written.map((w) => path.basename(w.src)));
    for (const f of fs.readdirSync(dir)) {
      if (!keep.has(f)) fs.unlinkSync(path.join(dir, f));
    }
    if (fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
  }

  report.push({ item, written, bad });
}

if (totalBytes > args.maxTotalMb * 1024 * 1024) {
  die(
    `wrote ${(totalBytes / 1048576).toFixed(1)} MB, over the --max-total-mb ${args.maxTotalMb} cap. ` +
      `Re-export the source photos smaller.`
  );
}

/* ── orphan folders ───────────────────────────────────────────────────────── */

const known = new Set(manifest.items.map((i) => i.code.toLowerCase()));
const orphans = fs.existsSync(OUT_ROOT)
  ? fs.readdirSync(OUT_ROOT, { withFileTypes: true })
      .filter((d) => d.isDirectory() && !known.has(d.name))
      .map((d) => d.name)
  : [];
for (const o of orphans) {
  if (args.pruneOrphans) {
    fs.rmSync(path.join(OUT_ROOT, o), { recursive: true, force: true });
    console.log(`pruned orphan folder ${o}/`);
  }
}

/* ── write JSON (surgical merge) ──────────────────────────────────────────── */

if (args.writeJson) {
  let count = 0;
  for (const { item, written } of report) {
    const row = rowByCode.get(item.code);
    if (written.length === 0) delete row.photos;
    else {
      // Strip the underscore-prefixed reporting fields before persisting.
      row.photos = written.map(({ _bytes, _quality, _from, ...keep }) => keep);
      count += written.length;
    }
  }
  // Photos for items outside --only keep whatever they already had.
  const untouched = data.rows
    .filter((r) => !targets.some((t) => t.code === r.code))
    .reduce((s, r) => s + (r.photos?.length ?? 0), 0);

  data._meta.photoCount = count + untouched;
  data._meta.photosSyncedAt = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(JSON_PATH, JSON.stringify(data, null, 2) + "\n");
}

/* ── report ───────────────────────────────────────────────────────────────── */

console.log();
for (const { item, written, bad } of report) {
  const kb = written.reduce((s, w) => s + w._bytes, 0) / 1024;
  const badTxt = bad.length ? `  ${bad.length} failed(${bad.map((b) => b.reason).join(",")})` : "";
  console.log(
    `${item.code.padEnd(8)} ${(item.name ?? "").slice(0, 26).padEnd(28)} ` +
      `${String(written.length).padStart(2)} ok${badTxt}`.padEnd(26) +
      (written.length ? `→ ${item.code.toLowerCase()}/  ${Math.round(kb)} KB` : "")
  );
}

const totalPhotos = report.reduce((s, r) => s + r.written.length, 0);
console.log(
  `\n${report.length} items · ${totalPhotos} photos · ` +
    `${(totalBytes / 1048576).toFixed(1)} MB written · ${problems.length} problem(s)`
);

const oversized = report.flatMap((r) => r.written.filter((w) => w._bytes > SOFT_MAX_BYTES));
for (const w of oversized) {
  console.warn(`WARN  ${w.src} is ${Math.round(w._bytes / 1024)}KB even at q${w._quality}`);
}
for (const o of orphans) {
  if (!args.pruneOrphans) {
    console.warn(`WARN  public/images/equipment/${o}/ is not in the manifest (--prune-orphans to delete)`);
  }
}

if (problems.length) {
  console.error("\nFAILED:");
  for (const p of problems) {
    console.error(`  ${p.code}  ${p.file}  [${p.reason}] ${p.message}`);
  }
  if (problems.some((p) => p.reason === "EXPIRED")) {
    console.error(
      "\nEXPIRED means the signed Notion URLs aged out (~1h). Re-read the page,\n" +
        "regenerate the manifest, then re-run with --only <codes>."
    );
  }
  if (problems.some((p) => p.reason === "HEIC")) {
    console.error("\nHEIC: ask the client to re-export those as JPEG in Notion.");
  }
  // Non-zero on partial success is deliberate — an incomplete sync must not
  // slip through the gate unnoticed.
  process.exit(1);
}

console.log(
  "\nNext:  npm run validate:equipment\n" +
    "       npx tsc --noEmit && npm run build"
);
